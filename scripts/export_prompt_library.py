"""Write the prompt library (docs/ai/prompt-library.md) from the code that actually sends the prompts.

    python scripts/export_prompt_library.py

The document lists, per phase, the candidate model, prompt and schema versions, the system prompt,
the user-message shape and the JSON schema decoding is constrained to. It is generated, so it cannot
drift from packages/ai/assureops_ai/prompts.py and registry.py.
"""

import json
from pathlib import Path

from assureops_ai import prompts
from assureops_ai.registry import PHASES, SCHEMAS

OUT = Path(__file__).resolve().parent.parent / "docs" / "ai" / "prompt-library.md"


def main():
    lines = ["# Prompt library", "",
             "Generated by `scripts/export_prompt_library.py` from `packages/ai/assureops_ai/prompts.py` and `registry.py`; do not edit by hand.", "",
             "Every phase only proposes. Outputs are validated against the schema below (decoding is constrained to it where the",
             "serving runtime supports that), checked against the cited sources, and accepted or rejected by a person other than the",
             "requester. No model output decides a test result, evidence validity, an approval or a release gate.", ""]
    for phase in PHASES.values():
        lines += [f"## Phase {phase.id}: {phase.name.replace('_', ' ')}", "",
                  f"- Candidate: `{phase.candidate}` ({phase.parameters}), kind `{phase.kind}`",
                  f"- Prompt version `{phase.prompt_version}`, schema version `{phase.schema_version}`",
                  f"- Purpose: {phase.purpose}", ""]
        system = prompts.SYSTEM.get(phase.id)
        if system:
            lines += ["System prompt:", "", "```text", system.strip(), "```", ""]
            lines += ["User message: `prompts.user_message(phase, data)` serialises the phase inputs (sources, tests, facts) as JSON after a",
                      "short instruction; inputs are rebuilt by the worker from references, never taken from the browser.", ""]
        else:
            lines += ["No generative prompt: this phase calls an encoder (embedding, NLI classification or screening) on bounded inputs.", ""]
        schema = SCHEMAS.get(phase.id)
        if schema:
            lines += ["Output schema:", "", "```json", json.dumps(schema, indent=1), "```", ""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(OUT.parents[2])}")


if __name__ == "__main__":
    main()
