"""Create infra/compose/dev.env with fresh random local test values (first run and CI).

    python scripts/init_dev_env.py

Never overwrites an existing file. Values are generated here, written only to the
git-ignored dev.env and never printed. The render scripts add the rest:
render_realm.py (staff TOTP secrets), render_storage.py (object store identity),
render_web_env.py (portal session key). Model and Groq settings are opt-in and
added by the operator.
"""

import base64
import os
import secrets
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ENV_FILE = ROOT / "infra" / "compose" / "dev.env"


def token(n: int = 24) -> str:
    return secrets.token_urlsafe(n)


def main():
    if ENV_FILE.exists():
        print(f"{ENV_FILE.relative_to(ROOT)} already exists; left unchanged")
        return
    values = {
        "POSTGRES_SUPERUSER_PASSWORD": token(),
        "ASSUREOPS_OWNER_PASSWORD": token(),
        "ASSUREOPS_APP_PASSWORD": token(),
        "KEYCLOAK_ADMIN_PASSWORD": token(),
        "CUSTOMER_WEB_CLIENT_SECRET": token(32),
        "STAFF_WEB_CLIENT_SECRET": token(32),
        "DEMO_USER_PASSWORD": "Demo-" + token(12),
        "SESSION_SECRET": token(32),
        "RUNNER_SERVICE_TOKEN": token(32),
        "GATEWAY_SERVICE_TOKEN": token(32),
        "TOOLS_SERVICE_TOKEN": token(32),
        "AGENT_SOURCE_TOKEN": token(32),
        "TOOLS_SOURCE_TOKEN": token(32),
        "ASSUREOPS_SECRET_KEY": base64.urlsafe_b64encode(os.urandom(32)).decode(),  # Fernet key format
        "ALLOW_PRIVATE_TARGETS": "true",
        "RECEIPT_SIGNING_KEY": secrets.token_hex(32),
        "GITHUB_WEBHOOK_SECRET": secrets.token_hex(24),
        "RUN_TOKEN_KEY": secrets.token_hex(32),
        "STAFF_MFA_REQUIRED": "true",
    }
    ENV_FILE.parent.mkdir(parents=True, exist_ok=True)
    body = "# Local test values generated by scripts/init_dev_env.py. Git-ignored; never commit.\n"
    body += "".join(f"{k}={v}\n" for k, v in values.items())
    ENV_FILE.write_text(body, encoding="utf-8", newline="\n")
    print(f"wrote {ENV_FILE.relative_to(ROOT)} with {len(values)} generated values (not shown)")


if __name__ == "__main__":
    main()
