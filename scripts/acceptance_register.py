"""Build docs/acceptance/register.md from recorded test runs and the reviewed suite mapping (plan v6 section 3).

    .venv/Scripts/python -m pytest --junitxml var/test-results/pytest.xml
    npx playwright test --reporter=json > var/test-results/e2e.json
    python scripts/acceptance_register.py

Status per case is pass, fail, not_run or not_applicable. Executed cases take their status from the
recorded run; manual entries in docs/acceptance/suites.json carry their evidence and reason. A test
that exists but did not run in the recorded results is listed as not_run, never as passed.
"""

import json
import subprocess
import time
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "var" / "test-results"
OUT = ROOT / "docs" / "acceptance" / "register.md"


def pytest_cases() -> dict[str, str]:
    out = {}
    path = RESULTS / "pytest.xml"
    if not path.exists():
        return out
    for case in ET.parse(path).getroot().iter("testcase"):
        file = case.get("classname", "").replace(".", "/") + ".py"
        status = "fail" if case.find("failure") is not None or case.find("error") is not None else "not_run" if case.find("skipped") is not None else "pass"
        out[f"{file}::{case.get('name')}"] = status
    return out


def e2e_cases() -> dict[str, str]:
    out = {}
    path = RESULTS / "e2e.json"
    if not path.exists():
        return out
    data = json.loads(path.read_text(encoding="utf-8"))

    def walk(suite, prefix=""):
        for spec in suite.get("specs", []):
            results = [r for t in spec.get("tests", []) for r in t.get("results", [])]
            last = results[-1]["status"] if results else "skipped"
            out[f"e2e/{spec.get('file', suite.get('file', ''))}::{prefix}{spec['title']}"] = {"passed": "pass", "skipped": "not_run"}.get(last, "fail")
        for child in suite.get("suites", []):
            walk(child, prefix + (child["title"] + " > " if child.get("title") and not child["title"].endswith(".ts") else ""))
    for s in data.get("suites", []):
        walk(s)
    return out


def main():
    mapping = json.loads((ROOT / "docs" / "acceptance" / "suites.json").read_text(encoding="utf-8"))
    executed = {**pytest_cases(), **e2e_cases()}
    commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True, cwd=ROOT).stdout.strip()
    lines = ["# Acceptance register", "",
             f"Generated by `scripts/acceptance_register.py` on {time.strftime('%Y-%m-%d %H:%M')} from runs recorded on top of commit `{commit}`.",
             "Statuses: pass, fail, not_run, not_applicable. Writing a test is not passing it: only recorded results count.", "",
             f"> {mapping['note']}", ""]
    totals = {"pass": 0, "fail": 0, "not_run": 0, "not_applicable": 0}
    for suite in mapping["suites"]:
        rows = sorted((k, v) for k, v in executed.items() if any(k.replace("\\", "/").startswith(p) for p in suite["patterns"]))
        manual = suite.get("manual", [])
        counts = {s: sum(v == s for _, v in rows) + sum(m["status"] == s for m in manual) for s in totals}
        for s in totals:
            totals[s] += counts[s]
        lines += [f"## {suite['id']}: {suite['title']}", "", " · ".join(f"{k} {v}" for k, v in counts.items() if v) or "no recorded cases", "",
                  "| Case | Status | Evidence |", "|---|---|---|"]
        for name, status in rows:
            file, _, title = name.partition("::")
            lines.append(f"| {title} | {status} | `{file}` |")
        for m in manual:
            lines.append(f"| {m['case']} | {m['status']} | {m['evidence']} |")
        lines.append("")
    unique = {s: sum(v == s for v in executed.values()) for s in totals}  # a test mapped to two suites counts once here
    for suite in mapping["suites"]:
        for m in suite.get("manual", []):
            unique[m["status"]] += 1
    totals = unique
    lines[4:4] = ["Totals (each case once): " + " · ".join(f"{k} {v}" for k, v in totals.items()), ""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}: " + ", ".join(f"{k} {v}" for k, v in totals.items()))


if __name__ == "__main__":
    main()
